#!/usr/bin/env python3
"""Copy only FreeDigi's opted-in Chaiky Rust components from a local checkout.
Usage: python3 native/scripts/vendor-theme.py /path/to/core
No network access. Selection lives in native/Cargo.toml, not upstream defaults.
"""
import hashlib
import json
import re
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import tomllib

native = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1]).resolve()
theme = source / "js/packages/theme"
app = tomllib.loads((native / "Cargo.toml").read_text())
selected = set(app["dependencies"]["chaiky-egui"].get("features", []))
manifest = tomllib.loads((theme / "Cargo.toml").read_text())
features = manifest["features"]
# A new upstream feature is never enabled implicitly. Follow only dependencies
# of the explicit selection. 'gallery' is development-only, never vendored.
if "gallery" in selected or "default" in selected:
    raise SystemExit("Choose individual production components, not gallery/default")
required = set(selected)
queue = list(selected)
while queue:
    feature = queue.pop()
    if feature not in features:
        raise SystemExit(f"Unknown component: {feature}")
    for dependency in features[feature]:
        if dependency.startswith("dep:"):
            continue
        if dependency not in required:
            required.add(dependency)
            queue.append(dependency)
files = ["rust/lib.rs", "palette.json"]
files += [f"rust/{name}.rs" for name in sorted(required)]
if "mascot" in required:
    files.append("gull.svg")
revision = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
dirty = bool(subprocess.check_output(["git", "-C", str(source), "status", "--porcelain", "--", "js/packages/theme"], text=True).strip())
# Construct a minimal manifest: no examples, dev dependencies or unused features.
lines = ['# Generated by native/scripts/vendor-theme.py; edit the owning Chaiky source.']
for table in ["package", "lib"]:
    lines += [f"[{table}]"]
    for k, v in manifest[table].items():
        lines += [f'{k} = {json.dumps(v)}']
lines += ['[features]', 'default = []']
for name in sorted(required):
    lines += [f'{name} = {json.dumps(features[name])}']
for name, spec in manifest["dependencies"].items():
    if isinstance(spec, dict) and spec.get("optional") and not any(f"dep:{name}" in features[f] for f in required):
        continue
    if isinstance(spec, str):
        lines += [f'[dependencies.{name}]', f'version = {json.dumps(spec)}']
    else:
        lines += [f'[dependencies.{name}]']
        lines += [f'{k} = {json.dumps(v)}' for k, v in spec.items()]
# Replace just this generated directory: obsolete components disappear on update.
destination = native / "vendor/chaiky-theme"
with tempfile.TemporaryDirectory(dir=native / "vendor") as temp:
    stage = Path(temp) / "chaiky-theme"
    stage.mkdir()
    hashes = {}
    for name in files:
        target = stage / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(theme / name, target)
        hashes[name] = hashlib.sha256(target.read_bytes()).hexdigest()
    # Remove declarations for modules deliberately absent from the subset. This
    # also prevents unknown-feature warnings and accidentally enabling them.
    base = stage / "rust/lib.rs"
    content = base.read_text()
    for component in set(features) - required:
        content = re.sub(r'#\[cfg\(feature = "' + re.escape(component) + r'"\)\]\nmod [a-z_]+;\n', '', content)
    content = re.sub(r'#\[cfg\(all\(test, feature = "gallery"\)\)\]\nmod tests;\n', '', content)
    base.write_text(content.rstrip() + "\n")
    source_hashes = hashes.copy()
    hashes["rust/lib.rs"] = hashlib.sha256(base.read_bytes()).hexdigest()
    (stage / "Cargo.toml").write_text("\n".join(lines) + "\n")
    (stage / "PROVENANCE.json").write_text(json.dumps({"source": "Chaiky Core / js/packages/theme", "revision": revision, "uncommitted_source": dirty, "selected_components": sorted(selected), "included_components": sorted(required), "source_sha256": source_hashes, "vendored_sha256": hashes}, indent=2) + "\n")
    if destination.exists():
        shutil.rmtree(destination)
    shutil.move(str(stage), destination)
print(f"Vendored {len(required)} components ({len(files)} source/assets); source {revision}, dirty={dirty}")
